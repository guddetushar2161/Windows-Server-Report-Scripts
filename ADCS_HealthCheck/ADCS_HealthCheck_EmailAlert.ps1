#Requires -Version 5.1
<#
.SYNOPSIS
    Email alert companion for ADCS_HealthCheck.ps1

.DESCRIPTION
    Reads the plain-text status files (_CRITICAL.txt / _HEALTHY.txt) generated by
    ADCS_HealthCheck.ps1 and sends a formatted HTML email notification via SMTP.

    A built-in -TestEmail switch verifies SMTP connectivity end-to-end before you
    rely on scheduled alerts — if the test email arrives, the SMTP settings are
    correct and real alerts will work.

.EXAMPLE
    # Verify SMTP settings (no status file required)
    .\ADCS_HealthCheck_EmailAlert.ps1 -TestEmail

    # Send real alerts (reads latest ADC_Health_*_CRITICAL.txt)
    .\ADCS_HealthCheck_EmailAlert.ps1

    # Pass credentials securely at runtime
    .\ADCS_HealthCheck_EmailAlert.ps1 -SmtpCredential (Get-Credential)

    # Process a specific status file
    .\ADCS_HealthCheck_EmailAlert.ps1 -StatusFile 'C:\Reports\ADC_Health_20260309_CRITICAL.txt'

    # Scan a custom reports folder
    .\ADCS_HealthCheck_EmailAlert.ps1 -ReportsFolder 'D:\PKIReports'

.PARAMETER TestEmail
    Sends a single test email to verify SMTP connectivity.
    No status file is required.

.PARAMETER StatusFile
    Full path to a specific status file to process.

.PARAMETER ReportsFolder
    Path to the folder containing ADC_Health_* status files.
    Defaults to the 'Reports' subfolder next to this script.

.PARAMETER SmtpCredential
    A PSCredential for SMTP authentication.
    Preferred over plain-text credentials stored in this script.

.NOTES
    Version    : 1.0.0
    Author     : Tushar Gudde
    Requires   : PowerShell 5.1+, SMTP relay accessible from this server
    Companion  : ADCS_HealthCheck.ps1  (set $EnableStatusFile = $true)
#>

param(
    [switch]$TestEmail,
    [string]$StatusFile    = '',
    [string]$ReportsFolder = '',
    [System.Management.Automation.PSCredential]$SmtpCredential = $null
)

# ════════════════════════════════════════════════════════════════════════════════
# CONFIGURATION
# ════════════════════════════════════════════════════════════════════════════════

$SmtpServer  = 'smtp.yourdomain.com'
$SmtpPort    = 587
$SmtpUseSsl  = $true

# Preferred: pass -SmtpCredential (Get-Credential) on the command line.
$SmtpUsername = ''
$SmtpPassword = ''

$FromAddress = 'pkihealth@yourdomain.com'
$ToAddresses = @('admin@yourdomain.com')
$CcAddresses = @()

$AlertOnCritical  = $true
$AlertOnHealthy   = $false
$MaxFilesToProcess = 1

# ════════════════════════════════════════════════════════════════════════════════

$ScriptVersion = '1.0.0'
$ScriptDir     = Split-Path -Parent $MyInvocation.MyCommand.Definition
if ([string]::IsNullOrEmpty($ScriptDir)) { $ScriptDir = $PWD.Path }

# ── HELPER FUNCTIONS ──────────────────────────────────────────────────────────
function Write-Log {
    param([string]$Msg, [string]$Color = 'Cyan')
    Write-Host "  [$(Get-Date -Format 'HH:mm:ss')] $Msg" -ForegroundColor $Color
}

function HtmlEscape {
    param([string]$Text)
    if ([string]::IsNullOrEmpty($Text)) { return '' }
    $Text = $Text -replace '&', '&amp;'
    $Text = $Text -replace '<', '&lt;'
    $Text = $Text -replace '>', '&gt;'
    $Text = $Text -replace '"', '&quot;'
    $Text = $Text -replace "'", '&#39;'
    return $Text
}

function Build-HtmlEmail {
